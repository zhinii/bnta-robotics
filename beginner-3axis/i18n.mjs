const english = Object.create(null);
const chinese = Object.create(null);
for (const [key, englishText, chineseText] of entries) {
  if (Object.hasOwn(english, key))
    throw new Error(`Duplicate translation key: ${key}`);
  if (!englishText || !chineseText)
    throw new Error(`Incomplete translation: ${key}`);
  english[key] = englishText;
  chinese[key] = chineseText;
}
for (const [alias, source] of Object.entries(aliases)) {
  if (!Object.hasOwn(english, source) || Object.hasOwn(english, alias)) {
    throw new Error(`Invalid translation alias: ${alias}`);
  }
  english[alias] = english[source];
  chinese[alias] = chinese[source];
}

export const supportedLanguages = Object.freeze(["en", "zh"]);
export const en = Object.freeze(english);
export const zh = Object.freeze(chinese);
export const dictionaries = Object.freeze({ en, zh });

/** Resolve a stable key and interpolate own-property {parameters} as plain text.
 * Unknown languages choose the default English dictionary as a whole. Unknown
 * keys remain visibly marked; a Chinese missing key never borrows English copy.
 * Missing parameters remain visible to help locate incomplete UI wiring.
 */
export function t(language, key, params = {}) {
  const dictionary = Object.hasOwn(dictionaries, language)
    ? dictionaries[language]
    : en;
  if (!Object.hasOwn(dictionary, key)) return `[${String(key)}]`;
  return dictionary[key].replace(
    /\{([A-Za-z][A-Za-z0-9_]*)\}/g,
    (match, name) => {
      if (
        params === null ||
        typeof params !== "object" ||
        !Object.hasOwn(params, name)
      )
        return match;
      const value = params[name];
      return typeof value === "string" ||
        typeof value === "number" ||
        typeof value === "boolean"
        ? String(value)
        : match;
    },
  );
}
